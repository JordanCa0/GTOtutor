// Sanity review of the stack-depth charts (docs/stack-depths-plan.md, Phase 4), as a markdown report.
// Run from the repo root: npx tsx apps/api/scripts/reviewStackCharts.ts [manifest] > docs/stack-depths-review.md
//
// Checks: how wide each position opens and defends at 20, 60 and 100bb; whether a short seat at a
// deeper table plays like the equal-stacks chart of its depth; how much hands mix; and a few hands
// that should never fold or never play.
import { SIX_MAX_POSITIONS, type Position } from '@gtotutor/shared-types';
import { readFileSync } from 'node:fs';
import { ChartService } from '../src/charts/chartService.js';
import { loadSolvedCharts } from '../src/charts/solvedCharts.js';
import { parseProfile } from '../src/charts/stackProfile.js';
import type { ChartNode } from '../src/charts/types.js';
import { ALL_HAND_CLASSES, comboCount } from '../src/poker/cards.js';

const manifestPath = process.argv[2] ?? 'preflop/charts/stacks-v1.json';
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as { version: string; profiles: Record<string, string> };
const charts = new ChartService(loadSolvedCharts(manifestPath, { lazyMixed: true }), 200);
const profiles = Object.keys(manifest.profiles);
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const node = (key: string): ChartNode | null => (charts.hasNode(key) ? charts.getNode(key) : null);

/** Combo-weighted share of all hands that don't fold (or check) at a node. */
function playShare(n: ChartNode): number {
  const passive = n.actions.findIndex((a) => a.id === 'fold' || a.id === 'check');
  let played = 0;
  for (const hc of ALL_HAND_CLASSES) played += comboCount(hc) * (1 - (passive >= 0 ? n.strategy.get(hc)![passive] : 0));
  return played / 1326;
}

/** Share of the range taking each action, as "Fold 60%, Raise to 2 25%, All-in 20 15%". */
const mix = (n: ChartNode) => charts.rangeSummary(n).map((s, i) => `${n.actions[i].label} ${pct(s)}`).join(', ');

/** Combo-weighted half the summed difference between two nodes with the same actions (share of the range that plays differently). */
function diff(a: ChartNode, b: ChartNode): number | null {
  if (a.actions.length !== b.actions.length || a.actions.some((x, i) => x.id !== b.actions[i].id)) return null;
  let d = 0;
  for (const hc of ALL_HAND_CLASSES) {
    const fa = a.strategy.get(hc)!;
    const fb = b.strategy.get(hc)!;
    d += (comboCount(hc) / 1326) * fa.reduce((s, f, i) => s + Math.abs(f - fb[i]), 0) / 2;
  }
  return d;
}

/** Share of the range (by combos) whose top action is under 80%: genuinely mixed hands. */
function mixedShare(n: ChartNode): number {
  let m = 0;
  for (const hc of ALL_HAND_CLASSES) if (Math.max(...n.strategy.get(hc)!) < 0.8) m += comboCount(hc) / 1326;
  return m;
}

const out: string[] = [];
const say = (s = '') => out.push(s);

say(`# Stack-depth chart review (${manifest.version})`);
say();
say(`Generated by \`apps/api/scripts/reviewStackCharts.ts\` from \`${manifestPath}\` (${profiles.length} profiles). Numbers are shares of all 1326 combos.`);
say();

// 1. Opening (first in) by depth.
say('## First in: share of hands played (not folded)');
say();
say('| Position | 20bb | 60bb | 100bb |');
say('|---|---|---|---|');
for (const pos of SIX_MAX_POSITIONS.filter((p) => p !== 'BB')) {
  say(`| ${pos} | ${[20, 60, 100].map((d) => { const n = node(`SIX_MAX|${d}|RFI|${pos}`); return n ? pct(playShare(n)) : '–'; }).join(' | ')} |`);
}
say();
say('How each depth opens:');
say();
for (const d of [20, 60, 100]) for (const pos of ['UTG', 'BTN', 'SB'] as Position[]) {
  const n = node(`SIX_MAX|${d}|RFI|${pos}`);
  if (n) say(`- ${d}bb ${pos}: ${mix(n)}`);
}
say();

// 2. Defending the BB against a BTN open, and facing a shove at 20bb.
say('## Big blind defence');
say();
for (const d of [20, 60, 100]) {
  const n = node(`SIX_MAX|${d}|VS_OPEN|BB|BTN`);
  if (n) say(`- ${d}bb BB vs BTN open: ${mix(n)}`);
}
for (const vs of ['UTG', 'BTN', 'SB'] as Position[]) {
  const n = node(`SIX_MAX|20|VS_ALLIN|BB|${vs}`);
  if (n) say(`- 20bb BB vs ${vs} shove: ${mix(n)}`);
}
say();

// 3. Short seats at deeper tables against the equal-stacks chart of their depth.
say('## Short seats at deeper tables vs the equal-stacks chart');
say();
say("A short seat's first-in chart, compared with the same seat at an equal-stacks table of its own depth: the share of the range that plays differently. The plan expects these to be close; the deeper players behind (who can't win more than the short stack) explain some difference.");
say();
say('| Profile | Short seat | Compared with | Differs |');
say('|---|---|---|---|');
const shortRows: [string, string, string, number][] = [];
for (const p of profiles.filter((x) => x.includes(':'))) {
  const stacks = parseProfile(p)!;
  for (const pos of SIX_MAX_POSITIONS.filter((x) => x !== 'BB')) {
    const s = stacks[pos];
    if (s === Number(p.split(':')[0])) continue;
    const a = node(`SIX_MAX|${p}|RFI|${pos}`);
    const b = node(`SIX_MAX|${s}|RFI|${pos}`);
    const d = a && b ? diff(a, b) : null;
    if (d !== null) shortRows.push([p, `${pos} ${s}bb`, `${s}bb ${pos}`, d]);
  }
}
shortRows.sort((x, y) => y[3] - x[3]);
for (const [p, seat, cmp, d] of shortRows.slice(0, 12)) say(`| ${p} | ${seat} | ${cmp} | ${pct(d)} |`);
if (shortRows.length > 12) say(`| … ${shortRows.length - 12} more | | | median ${pct(shortRows[Math.floor(shortRows.length / 2)][3])} |`);
say();

// 4. Mixing.
say('## Mixed strategies');
say();
say('Share of the range with no action at 80% or more, per profile (first-in nodes, averaged over positions). High values on a node mean the solver is undecided there.');
say();
const mixRows = profiles.map((p) => {
  const ns = SIX_MAX_POSITIONS.filter((x) => x !== 'BB').map((pos) => node(`SIX_MAX|${p}|RFI|${pos}`)).filter((n): n is ChartNode => !!n);
  return [p, ns.reduce((s, n) => s + mixedShare(n), 0) / ns.length] as const;
});
mixRows.sort((a, b) => b[1] - a[1]);
say('| Profile | Mixed share |');
say('|---|---|');
for (const [p, m] of [...mixRows.slice(0, 5), ...mixRows.slice(-3)]) say(`| ${p} | ${pct(m)} |`);
say();

// 5. Hands that should never fold first in, and never play from early position.
say('## Spot checks');
say();
const problems: string[] = [];
for (const p of profiles) {
  for (const pos of SIX_MAX_POSITIONS.filter((x) => x !== 'BB')) {
    const n = node(`SIX_MAX|${p}|RFI|${pos}`);
    if (!n) continue;
    const fold = n.actions.findIndex((a) => a.id === 'fold');
    for (const hc of ['AA', 'KK', 'QQ', 'AKs']) if (n.strategy.get(hc)![fold] > 0.05) problems.push(`${p} ${pos} folds ${hc} ${pct(n.strategy.get(hc)![fold])} first in`);
    if (pos === 'UTG') for (const hc of ['72o', '83o', '92o']) if (n.strategy.get(hc)![fold] < 0.95) problems.push(`${p} UTG plays ${hc} ${pct(1 - n.strategy.get(hc)![fold])} first in`);
  }
}
say(problems.length ? problems.map((p) => `- ${p}`).join('\n') : '- No premium hand folds more than 5% first in, and UTG never plays 72o, 83o or 92o, in any profile.');
say();

console.log(out.join('\n'));
